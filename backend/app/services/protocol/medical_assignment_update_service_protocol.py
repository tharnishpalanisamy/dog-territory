from typing import Protocol

from app.models import MedicalAssignmentUpdate


class MedicalAssignmentUpdateServiceProtocol(Protocol):
    async def create_update(self, assignment_id: int, data, user) -> MedicalAssignmentUpdate: ...

    async def get_updates(self, assignment_id: int) -> list[MedicalAssignmentUpdate]: ...

    async def get_update_by_id(self, update_id: int) -> MedicalAssignmentUpdate: ...

    async def get_update_for_user(self, update_id: int, user) -> MedicalAssignmentUpdate: ...

    async def update_update(self, update_id: int, data, user) -> MedicalAssignmentUpdate: ...

    async def delete_update(self, update_id: int, user) -> None: ...
