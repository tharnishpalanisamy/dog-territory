from typing import Protocol

from app.models import MedicalAssignment


class MedicalAssignmentRepositoryProtocol(Protocol):
    async def create(self, assignment: MedicalAssignment) -> MedicalAssignment: ...

    async def get_all(self, filters, limit: int, offset: int) -> list[MedicalAssignment]: ...

    async def get_by_id(self, assignment_id: int) -> MedicalAssignment | None: ...

    async def get_by_work_assignment_id(
        self, work_assignment_id: int
    ) -> list[MedicalAssignment]: ...

    async def get_veterinarian_for_user(self, user_id: int): ...

    async def get_veterinarian_by_id(self, veterinarian_id: int): ...

    async def update(self, assignment: MedicalAssignment, fields: dict) -> MedicalAssignment: ...

    async def delete(self, assignment: MedicalAssignment) -> None: ...
