from collections.abc import Sequence

from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Dog
from app.schemas import DogFilterParams


class DogRepository:
    def __init__(self, db: AsyncSession):
        self.db = db

    async def create(self, dog: Dog) -> Dog:
        self.db.add(dog)
        await self.db.flush()
        await self.db.refresh(dog)

        return dog

    async def get_all(
        self, filters: DogFilterParams, limit: int, offset: int
    ) -> Sequence[Dog]:
        query = select(Dog) 

        conditions = [] 
        if filters.status is not None :
            conditions.append(
                Dog.status == filters.status
            )
        
        if filters.is_sterilized is not None:
            conditions.append(
                Dog.is_sterilized == filters.is_sterilized
            )

        if filters.vaccination_status is not None:
            conditions.append(
                Dog.vaccination_status == filters.vaccination_status
            )

        if filters.state is not None:
            conditions.append(
                Dog.state == filters.state
            )

        if filters.district is not None:
            conditions.append(
                Dog.district == filters.district
            )

        if filters.area_name is not None:
            conditions.append(
                Dog.area_name == filters.area_name
            )
        if filters.pincode is not None:
            conditions.append(
                Dog.pincode == filters.pincode
            )

        if filters.estimated_age_min is not None:
            conditions.append(
                Dog.estimated_age >= filters.estimated_age_min
            )

        if filters.estimated_age_max is not None:
            conditions.append(
                Dog.estimated_age <= filters.estimated_age_max
            )

        if conditions:
            query = query.where(*conditions)

        query = query.order_by(
            Dog.id.asc(),
        )
        query = query.limit(limit).offset(offset)

        
        result = await self.db.scalars(query) 

        return result.all()

    async def get_by_id(self, id) -> Dog | None:
        query = select(Dog).where(Dog.id == id)

        return await self.db.scalar(query)

    async def get_by_dog_code(self, dog_code: str) -> Dog | None:
        query = select(Dog).where(Dog.dog_code == dog_code)

        return await self.db.scalar(query)

    async def update_by_id(self, dog: Dog, fields: dict[str, object]) -> Dog:
        for field, value in fields.items():
            setattr(dog, field, value)

        await self.db.flush()
        # `updated_at` is generated by the database on update. Refresh it now
        # so response serialization does not trigger async I/O on attribute access.
        await self.db.refresh(dog)
        return dog

    async def update_by_dog_code(self, dog: Dog, fields: dict[str, object]) -> Dog:
        for field, value in fields.items():
            setattr(dog, field, value)

        await self.db.flush()
        await self.db.refresh(dog)
        return dog

    async def get_max_count(self, pin_code: str) -> int | None:
        query = select(func.max(Dog.dog_number)).where(Dog.pincode == pin_code)

        result = await self.db.scalar(query)
        return result

    async def delete_by_dog_code(self, dog_code: str):
        query = delete(Dog).where(Dog.dog_code == dog_code)

        return await self.db.execute(query)

    async def delete_by_id(self, id: int):
        query = delete(Dog).where(Dog.id == id)

        return await self.db.execute(query)
